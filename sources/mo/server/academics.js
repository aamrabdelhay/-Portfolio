export function listFaculties(university) {
  const universityKey = String(university || '').trim();
  return ACADEMICS[universityKey] ? Object.keys(ACADEMICS[universityKey]) : [];
}

export function listDepartments(university, faculty) {
  const faculties = ACADEMICS[String(university || '').trim()];
  return faculties && faculties[String(faculty || '').trim()] ? faculties[String(faculty || '').trim()] : [];
}

// Validates the full academic chain and returns trimmed values ready for
// storage. Throws an Arabic error message for whichever level is missing or
// inconsistent (e.g. a department that does not belong to the chosen faculty
// at the chosen university).
export function validateAcademics({university, faculty, department, year} = {}) {
  const u = String(university || '').trim();
  const f = String(faculty || '').trim();
  const d = String(department || '').trim();
  const y = String(year || '').trim();
  if (!UNIVERSITIES.includes(u)) throw Error('برجاء اختيار الجامعة من القائمة');
  if (!listFaculties(u).includes(f)) throw Error('برجاء اختيار الكلية من القائمة');
  if (!listDepartments(u, f).includes(d)) throw Error('برجاء اختيار القسم من القائمة');
  if (!STUDENT_YEARS.includes(y)) throw Error('برجاء اختيار الفرقة من القائمة (من الأولى حتى السادسة، أو خريج / طالب دراسات عليا)');
  return {university: u, faculty: f, department: d, year: y};
}
